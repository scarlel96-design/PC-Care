using System.Diagnostics;
using System.Text.Json;

namespace SmartPerformanceDoctor.App.Services.Commercial;

/// <summary>
/// A read-only, immediately-before-WinPE inspection. This is deliberately not a sanitizer:
/// it starts no firmware command, does not lock a volume, and does not change the selected disk.
/// </summary>
public interface IStoragePurgeReadOnlyInspector
{
    PurgeReadOnlyInspection Inspect(StorageSanitizeDryRunResult plan);
}

public enum PurgeInspectionState
{
    NotInspected,
    VerifiedReadOnly,
    TargetMismatch,
    ProbeFailed
}

public sealed class PurgeReadOnlyInspection
{
    public PurgeInspectionState State { get; init; }
    public DateTimeOffset InspectedAtUtc { get; init; }
    public string DeviceFingerprint { get; init; } = "";
    public string BusType { get; init; } = "Unknown";
    public string FirmwareVersion { get; init; } = "";
    public long SizeBytes { get; init; }
    public int? DiskNumber { get; init; }
    public bool IsBootDisk { get; init; }
    public bool IsSystemDisk { get; init; }
    public bool IsOffline { get; init; }
    public bool IsReadOnly { get; init; }
    public string Detail { get; init; } = "";
    public bool CanExecute => false;
    public bool IsFresh(DateTimeOffset now) => State == PurgeInspectionState.VerifiedReadOnly && InspectedAtUtc <= now && now - InspectedAtUtc <= TimeSpan.FromMinutes(5);
}

/// <summary>
/// Uses only Get-Disk/Get-PhysicalDisk read commands. Firmware sanitize bits are never inferred:
/// Windows inventory cannot prove an NVMe controller's SANICAP or command-effects-log values.
/// </summary>
public sealed class WindowsStoragePurgeReadOnlyInspector : IStoragePurgeReadOnlyInspector
{
    public PurgeReadOnlyInspection Inspect(StorageSanitizeDryRunResult plan)
    {
        var expected = DeviceFingerprint.Create(plan.Device);
        if (!plan.Device.IsResolved || string.IsNullOrWhiteSpace(expected))
            return Failed("물리 디스크 식별값이 없어 읽기 전용 재검증을 시작할 수 없습니다.");

        try
        {
            var disk = ProbeDisk(plan.Device.DiskNumber!.Value);
            if (disk is null) return Failed("Get-Disk 읽기 전용 조회에 실패했습니다.");
            var observed = new StorageDeviceIdentity
            {
                RootPath = plan.Device.RootPath, DriveLetter = plan.Device.DriveLetter,
                DiskNumber = disk.Number, UniqueId = disk.UniqueId, SerialNumber = disk.SerialNumber,
                Model = disk.Model, BusType = disk.BusType, SizeBytes = disk.SizeBytes,
                IsBootDisk = disk.IsBootDisk, IsSystemDisk = disk.IsSystemDisk,
                IsOffline = disk.IsOffline, IsReadOnly = disk.IsReadOnly
            };
            var observedFingerprint = DeviceFingerprint.Create(observed);
            if (!DeviceFingerprint.FixedTimeEquals(expected, observedFingerprint))
                return Observation(disk, observedFingerprint, PurgeInspectionState.TargetMismatch,
                    "Dry Run의 장치 지문과 현재 읽기 전용 조회 결과가 다릅니다. 대상 교체 가능성이 있어 이후 단계는 차단됩니다.");
            if (disk.IsOffline || disk.IsReadOnly)
                return Observation(disk, observedFingerprint, PurgeInspectionState.ProbeFailed,
                    "대상이 오프라인 또는 읽기 전용 상태입니다. 안전상 이후 단계를 차단합니다.");
            return Observation(disk, observedFingerprint, PurgeInspectionState.VerifiedReadOnly,
                "Disk 번호·고유 ID·시리얼·크기·버스 타입을 읽기 전용으로 재확인했습니다. 이는 펌웨어 Sanitize 지원 증명이 아닙니다.");
        }
        catch { return Failed("읽기 전용 저장소 조회 중 오류가 발생했습니다."); }
    }

    private static PurgeReadOnlyInspection Observation(DiskProbe disk, string fingerprint, PurgeInspectionState state, string detail) => new()
    {
        State = state, InspectedAtUtc = DateTimeOffset.UtcNow, DeviceFingerprint = fingerprint,
        DiskNumber = disk.Number, BusType = disk.BusType, SizeBytes = disk.SizeBytes,
        IsBootDisk = disk.IsBootDisk, IsSystemDisk = disk.IsSystemDisk,
        IsOffline = disk.IsOffline, IsReadOnly = disk.IsReadOnly, FirmwareVersion = disk.FirmwareVersion, Detail = detail
    };
    private static PurgeReadOnlyInspection Failed(string detail) => new() { State = PurgeInspectionState.ProbeFailed, InspectedAtUtc = DateTimeOffset.UtcNow, Detail = detail };

    private static DiskProbe? ProbeDisk(int number)
    {
        // The disk number is an integer generated by Get-Disk, not user-provided script text.
        var script = "$ErrorActionPreference='Stop'; $d=Get-Disk -Number " + number + "; $p=Get-PhysicalDisk | Where-Object { $_.UniqueId -eq $d.UniqueId } | Select-Object -First 1; [pscustomobject]@{Number=$d.Number;UniqueId=$d.UniqueId;SerialNumber=$d.SerialNumber;Model=$d.FriendlyName;BusType=$d.BusType;Size=$d.Size;IsBoot=$d.IsBoot;IsSystem=$d.IsSystem;IsOffline=$d.IsOffline;IsReadOnly=$d.IsReadOnly;FirmwareVersion=if($p){$p.FirmwareVersion}else{''}} | ConvertTo-Json -Compress";
        using var process = Process.Start(new ProcessStartInfo
        {
            FileName = "powershell.exe", Arguments = "-NoProfile -NonInteractive -ExecutionPolicy Bypass -Command \"" + script + "\"",
            UseShellExecute = false, RedirectStandardOutput = true, RedirectStandardError = true, CreateNoWindow = true
        });
        if (process is null) return null;
        var output = process.StandardOutput.ReadToEnd();
        if (!process.WaitForExit(6000)) { try { process.Kill(true); } catch { } return null; }
        if (process.ExitCode != 0 || string.IsNullOrWhiteSpace(output)) return null;
        using var json = JsonDocument.Parse(output);
        var value = json.RootElement;
        return new DiskProbe(GetInt(value, "Number"), Get(value, "UniqueId"), Get(value, "SerialNumber"), Get(value, "Model"), Get(value, "BusType", "Unknown"), GetLong(value, "Size"), GetBool(value, "IsBoot"), GetBool(value, "IsSystem"), GetBool(value, "IsOffline"), GetBool(value, "IsReadOnly"), Get(value, "FirmwareVersion"));
    }

    private static string Get(JsonElement value, string name, string fallback = "") => value.TryGetProperty(name, out var property) && property.ValueKind is not JsonValueKind.Null ? property.ToString() : fallback;
    private static int? GetInt(JsonElement value, string name) => value.TryGetProperty(name, out var property) && property.TryGetInt32(out var result) ? result : null;
    private static long GetLong(JsonElement value, string name) => value.TryGetProperty(name, out var property) && property.TryGetInt64(out var result) ? result : 0;
    private static bool GetBool(JsonElement value, string name) => value.TryGetProperty(name, out var property) && property.ValueKind is JsonValueKind.True or JsonValueKind.False && property.GetBoolean();
    private sealed record DiskProbe(int? Number, string UniqueId, string SerialNumber, string Model, string BusType, long SizeBytes, bool IsBootDisk, bool IsSystemDisk, bool IsOffline, bool IsReadOnly, string FirmwareVersion);
}